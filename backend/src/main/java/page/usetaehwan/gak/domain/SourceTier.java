package page.usetaehwan.gak.domain;

/**
 * 출처 등급. <b>같은 문장이라도 누가 말했느냐로 무게가 다르다</b>는 걸 화면이 표시할 수
 * 있게 하는 값이다.
 *
 * <p>"공식 발표"와 "이적 소문"이 같은 크기로 나란히 놓이면, 우리가 둘을 같은 것으로
 * 취급한다는 뜻이 된다. 우리는 어느 쪽도 주장하지 않지만, <b>누가 말했는지는 옮긴다.</b>
 *
 * <h2>지금은 전부 {@link #MEDIA}다</h2>
 * <p>맨유 공식 RSS가 존재하지 않는다(여러 경로로 재확인). 그래서 {@link #OFFICIAL}은
 * 지금 쓰이는 데가 없다. 그래도 컬럼을 미리 두는 이유는, 공식 소스가 생겼을 때
 * <b>스키마 변경 없이 등급만 채우면 되게</b> 하려는 것이다. 반대로 나중에 컬럼을 더하면
 * 그때까지 쌓인 기록은 전부 등급이 비어 버린다.
 */
public enum SourceTier {

	/** 구단·리그·협회의 공식 채널. 자기 자신에 대해 말하는 1차 출처다. */
	OFFICIAL,

	/** 언론. 취재와 추측이 섞여 있고, 그 구분은 우리가 하지 않는다. */
	MEDIA
}
