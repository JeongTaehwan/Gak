package page.usetaehwan.gak.domain;

/**
 * 한 번의 동기화 시도 결과.
 */
public enum SyncStatus {
	/** 응답을 받아 DB에 반영 완료. */
	SUCCESS,
	/** 통신 실패·플랜 제한·매핑 실패 등으로 반영하지 못함. 다음 주기에 다시 시도한다. */
	FAILED,
	/**
	 * 시도조차 하지 않음 — 일일 요청 예산 소진, 또는 재생 모드에서 응답 파일이 없는 경우.
	 *
	 * <p>예산 소진은 이력에 저장한다(그날 무엇을 못 했는지가 정보다).
	 * 반면 재생 파일 없음은 저장하지 않고 로그로만 남긴다 — 파일을 채우기 전까지 매 주기
	 * 반복될 사실이라, 쌓아 두면 진짜 실패가 그 안에 묻힌다.
	 */
	SKIPPED
}
